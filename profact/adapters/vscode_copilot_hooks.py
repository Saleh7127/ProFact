"""VS Code GitHub Copilot agent-hook capture adapter.

VS Code invokes workspace hooks as short-lived command processes. Its hook
contract provides a session id and a timestamp but no turn id, so ProFact uses
the ``UserPromptSubmit`` timestamp as the durable generation key and resolves
``Stop`` against the open turn for that session. The contract does not expose
assistant responses, reasoning, model metadata, or token usage; those fields
remain unavailable rather than being inferred from the unstable transcript.
"""

from __future__ import annotations

import json
import os
import shlex
import stat
import sys
from pathlib import Path

from .. import store
from . import hook_capture

EVENT_PROMPT = "UserPromptSubmit"
EVENT_STOP = "Stop"
HANDLED_EVENTS = (EVENT_PROMPT, EVENT_STOP)

CONFIG_REL = ".github/hooks/profact.json"
SHELL_RUNNER_REL = ".github/hooks/profact-vscode-hook.sh"
WINDOWS_RUNNER_REL = ".github/hooks/profact-vscode-hook.cmd"


def install(repo_root: Path) -> tuple[str, str]:
    """Install project-local VS Code Copilot hooks without replacing others."""
    config_path = repo_root / CONFIG_REL
    config: dict = {"hooks": {}}
    if config_path.exists():
        try:
            loaded = json.loads(config_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise ValueError(f"invalid VS Code hooks JSON: {config_path}") from exc
        if not isinstance(loaded, dict):
            raise ValueError(f"VS Code hooks config must be an object: {config_path}")
        config = loaded

    hooks = config.setdefault("hooks", {})
    if not isinstance(hooks, dict):
        raise ValueError(f"VS Code hooks must be an object: {config_path}")
    for event_name in HANDLED_EVENTS:
        entries = hooks.setdefault(event_name, [])
        if not isinstance(entries, list):
            raise ValueError(f"VS Code {event_name} hooks must be a list: {config_path}")

    hooks_dir = config_path.parent
    hooks_dir.mkdir(parents=True, exist_ok=True)
    shell_path = repo_root / SHELL_RUNNER_REL
    windows_path = repo_root / WINDOWS_RUNNER_REL
    package_parent = Path(__file__).resolve().parent.parent.parent
    shell_package_parent = shlex.quote(package_parent.as_posix())
    shell_python = shlex.quote(Path(sys.executable).as_posix())
    shell_path.write_text(
        "#!/usr/bin/env bash\n"
        "# Auto-generated by `profact start --copilot`.\n"
        f"export PYTHONPATH={shell_package_parent}${{PYTHONPATH:+:$PYTHONPATH}}\n"
        f"exec {shell_python} -m profact.cli copilot-hook\n",
        encoding="utf-8",
        newline="\n",
    )
    shell_path.chmod(
        shell_path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH
    )
    windows_path.write_text(
        "@echo off\n"
        f'set "PYTHONPATH={package_parent};%PYTHONPATH%"\n'
        f'"{sys.executable}" -m profact.cli copilot-hook\n',
        encoding="utf-8",
        newline="\r\n",
    )

    windows_runner = WINDOWS_RUNNER_REL.replace("/", "\\")
    handler = {
        "type": "command",
        "command": f'"./{SHELL_RUNNER_REL}"',
        "windows": f'".\\{windows_runner}"',
        "cwd": ".",
        "timeout": 30,
    }
    for event_name in HANDLED_EVENTS:
        entries = hooks[event_name]
        if not _has_profact_handler(entries, shell_path, windows_path):
            entries.append(dict(handler))

    config_path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    _ensure_gitignore(repo_root, CONFIG_REL, SHELL_RUNNER_REL, WINDOWS_RUNNER_REL)
    runner = WINDOWS_RUNNER_REL if os.name == "nt" else SHELL_RUNNER_REL
    return CONFIG_REL, runner


def handle(repo_root: Path, event: dict) -> dict:
    """Apply one VS Code agent-hook event and always return non-steering JSON."""
    if not store.is_initialized(repo_root):
        return {}

    conversation_id, generation_id = _identity(event)
    if not conversation_id:
        return {}
    event_name = event.get("hook_event_name")
    if event_name == EVENT_PROMPT:
        prompt = event.get("prompt")
        if not generation_id or not isinstance(prompt, str):
            return {}
        hook_capture.open_prompt(
            repo_root,
            conversation_id=conversation_id,
            generation_id=generation_id,
            prompt_text=prompt,
            model=None,
            superseded_source="vscode-copilot-superseded",
        )
    elif event_name == EVENT_STOP:
        finalized = hook_capture.finalize_turn(
            repo_root,
            conversation_id=conversation_id,
            generation_id=None,
            completion_source="vscode-copilot-stop",
        )
        if not finalized and event.get("stop_hook_active") is True:
            hook_capture.refresh_finalized_turn(
                repo_root,
                conversation_id=conversation_id,
                completion_source="vscode-copilot-stop",
            )
        hook_capture.reconcile_if_idle(repo_root)
    return {}


def _identity(event: dict) -> tuple[str | None, str | None]:
    session_id = event.get("session_id")
    timestamp = event.get("timestamp")
    conversation = (
        f"vscode-copilot-{session_id}"
        if session_id is not None and session_id != ""
        else None
    )
    generation = (
        str(timestamp) if timestamp is not None and timestamp != "" else None
    )
    return conversation, generation


def _has_profact_handler(
    entries: list, shell_path: Path, windows_path: Path
) -> bool:
    runner_names = {shell_path.name, windows_path.name}
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        commands = (entry.get("command"), entry.get("windows"))
        if any(
            isinstance(command, str)
            and any(runner_name in command for runner_name in runner_names)
            for command in commands
        ):
            return True
    return False


def _ensure_gitignore(repo_root: Path, *entries: str) -> None:
    gitignore = repo_root / ".gitignore"
    lines = gitignore.read_text().splitlines() if gitignore.exists() else []
    to_add = [entry for entry in entries if entry not in lines]
    if not to_add:
        return
    with gitignore.open("a", encoding="utf-8") as handle:
        if lines and lines[-1].strip():
            handle.write("\n")
        for entry in to_add:
            handle.write(f"{entry}\n")
