"""Codex CLI/IDE lifecycle-hook capture adapter.

Codex runs project-local command hooks as short-lived processes. The official
``session_id`` and ``turn_id`` fields map directly to ProFact conversation and
generation identity; ``last_assistant_message`` on Stop supplies the final
response. Filesystem artifacts still come from ProFact's Git tree snapshots.
"""

from __future__ import annotations

import json
import os
import shlex
import stat
import sys
from pathlib import Path

from .. import privacy, store
from . import hook_capture

EVENT_PROMPT = "UserPromptSubmit"
EVENT_STOP = "Stop"
EVENT_SESSION_END = "SessionEnd"
HANDLED_EVENTS = (EVENT_PROMPT, EVENT_STOP, EVENT_SESSION_END)



def install(repo_root: Path) -> tuple[str, str]:
    """Install and idempotently merge project-local Codex hooks.

    Returns repository-relative paths for the config and platform runner.
    Existing unrelated hooks and matcher groups are preserved.
    """
    codex_dir = repo_root / ".codex"
    hooks_dir = codex_dir / "hooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)
    _ensure_gitignore(repo_root, ".codex/hooks.json", ".codex/hooks/")

    package_parent = Path(__file__).resolve().parent.parent.parent
    shell_package_parent = shlex.quote(package_parent.as_posix())
    shell_python = shlex.quote(Path(sys.executable).as_posix())
    shell_rel = ".codex/hooks/profact-hook.sh"
    shell_path = repo_root / shell_rel
    shell_path.write_text(
        "#!/usr/bin/env bash\n"
        "# Auto-generated by `profact start --codex`.\n"
        f"export PYTHONPATH={shell_package_parent}${{PYTHONPATH:+:$PYTHONPATH}}\n"
        f"exec {shell_python} -m profact.cli codex-hook\n",
        encoding="utf-8",
    )
    shell_path.chmod(
        shell_path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH
    )

    command_rel = ".codex/hooks/profact-hook.cmd"
    command_path = repo_root / command_rel
    command_path.write_text(
        "@echo off\r\n"
        f'set "PYTHONPATH={package_parent};%PYTHONPATH%"\r\n'
        f'"{sys.executable}" -m profact.cli codex-hook\r\n',
        encoding="utf-8",
    )

    entry = {
        "type": "command",
        "command": f'"{shell_path.as_posix()}"',
        "commandWindows": f'"{command_path}"',
    }
    config_rel = ".codex/hooks.json"
    config_path = repo_root / config_rel
    config: dict = {
        "description": "ProFact prompt/artifact capture hooks.",
        "hooks": {},
    }
    if config_path.exists():
        try:
            loaded = json.loads(config_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise ValueError(f"invalid Codex hooks JSON: {config_path}") from exc
        if not isinstance(loaded, dict):
            raise ValueError(f"Codex hooks config must be an object: {config_path}")
        config = loaded
    config.setdefault("description", "ProFact prompt/artifact capture hooks.")
    hooks = config.setdefault("hooks", {})
    if not isinstance(hooks, dict):
        raise ValueError(f"Codex hooks must be an object: {config_path}")

    for event_name in HANDLED_EVENTS:
        groups = hooks.setdefault(event_name, [])
        if not isinstance(groups, list):
            raise ValueError(f"Codex {event_name} hooks must be a list: {config_path}")
        if _has_profact_handler(groups, shell_path, command_path):
            continue
        handler = dict(entry)
        handler["timeout"] = 3 if event_name == EVENT_SESSION_END else 30
        groups.append({"hooks": [handler]})

    config_path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    runner = command_rel if os.name == "nt" else shell_rel
    return config_rel, runner



def handle(repo_root: Path, event: dict) -> dict:
    """Apply one Codex hook event; always return non-steering JSON."""
    _record_debug_event(repo_root, event)
    if not store.is_initialized(repo_root):
        return {}

    conversation_id, generation_id = _identity(event)
    if not conversation_id:
        return {}
    name = event.get("hook_event_name")
    if name == EVENT_PROMPT:
        if not generation_id:
            return {}
        hook_capture.open_prompt(
            repo_root,
            conversation_id=conversation_id,
            generation_id=generation_id,
            prompt_text=event.get("prompt") or "",
            model=event.get("model"),
            superseded_source="codex-superseded",
        )
    elif name == EVENT_STOP:
        if not generation_id:
            return {}
        response = event.get("last_assistant_message")
        if isinstance(response, str) and response:
            hook_capture.append_response(
                repo_root,
                conversation_id=conversation_id,
                generation_id=generation_id,
                text=response,
                model=event.get("model"),
                deduplicate=True,
            )
        hook_capture.finalize_turn(
            repo_root,
            conversation_id=conversation_id,
            generation_id=generation_id,
            completion_source="codex-stop",
        )
    elif name == EVENT_SESSION_END:
        hook_capture.finalize_turn(
            repo_root,
            conversation_id=conversation_id,
            generation_id=None,
            completion_source="codex-session-end",
        )
        hook_capture.reconcile_if_idle(repo_root)
    return {}



def _identity(event: dict) -> tuple[str | None, str | None]:
    session_id = event.get("session_id")
    turn_id = event.get("turn_id")
    conversation = (
        f"codex-{session_id}" if session_id is not None and session_id != "" else None
    )
    generation = str(turn_id) if turn_id is not None and turn_id != "" else None
    return conversation, generation



def _has_profact_handler(
    groups: list, shell_path: Path, command_path: Path
) -> bool:
    expected = {str(shell_path), shell_path.as_posix(), str(command_path)}
    for group in groups:
        if not isinstance(group, dict):
            continue
        handlers = group.get("hooks", [])
        if not isinstance(handlers, list):
            continue
        for handler in handlers:
            if not isinstance(handler, dict):
                continue
            commands = (handler.get("command"), handler.get("commandWindows"))
            if any(
                isinstance(command, str)
                and command.strip('"') in expected
                for command in commands
            ):
                return True
    return False



def _ensure_gitignore(repo_root: Path, *entries: str) -> None:
    gitignore = repo_root / ".gitignore"
    lines = gitignore.read_text().splitlines() if gitignore.exists() else []
    to_add = [entry for entry in entries if entry not in lines]
    if not to_add:
        return
    with gitignore.open("a", encoding="utf-8") as handle:
        if lines and lines[-1].strip():
            handle.write("\n")
        for entry in to_add:
            handle.write(f"{entry}\n")



def _record_debug_event(repo_root: Path, event: dict) -> None:
    if not os.environ.get("PROFACT_CODEX_HOOK_DEBUG"):
        return
    try:
        log_path = store.profact_dir(repo_root) / "codex-hook-events.log"
        log_path.parent.mkdir(parents=True, exist_ok=True)
        redacted = _redact_debug_value(repo_root, event)
        with log_path.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(redacted) + "\n")
    except Exception:
        pass


def _redact_debug_value(repo_root: Path, value):
    if isinstance(value, str):
        return privacy.redact_for(repo_root, value)[0]
    if isinstance(value, list):
        return [_redact_debug_value(repo_root, item) for item in value]
    if isinstance(value, dict):
        return {
            key: _redact_debug_value(repo_root, item)
            for key, item in value.items()
        }
    return value
