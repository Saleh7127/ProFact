"""Cursor Hooks capture adapter (primary).

Cursor invokes a hook as a short-lived process per event, so this adapter holds
no in-memory state: each call is a direct, idempotent write to the profact store.
The only state carried between events is *which version is currently open* — the
HEAD prompt version whose ``tree_after`` is still NULL (LOCKED decision (b)).

Event flow for one user turn:
    beforeSubmitPrompt  -> open a `prompt` version, snapshot tree_before, move HEAD
    afterAgentThought   -> append the model's reasoning to the open version
    afterAgentResponse  -> append the assistant text to the open version
    stop / sessionEnd   -> snapshot tree_after, compute the diff, finalize

Reasoning ("thinking") is captured only for models that emit structured thinking
blocks; `afterAgentThought` never fires for non-reasoning models. A turn that
finalizes without any thinking is stamped ``thinking_source = 'none'`` so history
honestly records that reasoning was unavailable rather than merely unrecorded.

Diffs come from Git-tree snapshots (same mechanism as the proxy path), so
`afterFileEdit` is not required for capture and is intentionally not wired.
"""
from __future__ import annotations

import json
import os
import sqlite3
import stat
import sys
from pathlib import Path

from .. import git_ops, human_edits, store

EVENT_PROMPT = "beforeSubmitPrompt"
EVENT_THOUGHT = "afterAgentThought"
EVENT_RESPONSE = "afterAgentResponse"
EVENT_STOP = "stop"
EVENT_SESSION_END = "sessionEnd"

# Events profact registers in .cursor/hooks.json (see cli.start).
HANDLED_EVENTS = (
    EVENT_PROMPT,
    EVENT_THOUGHT,
    EVENT_RESPONSE,
    EVENT_STOP,
    EVENT_SESSION_END,
)


def install(repo_root: Path) -> str:
    """Install the project-local Cursor hook runner and merge its configuration.

    Returns the repository-relative path of the generated runner. Existing,
    unrelated hooks are preserved and profact entries are added idempotently.
    """
    cursor_dir = repo_root / ".cursor"
    hooks_dir = cursor_dir / "hooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)

    # These files contain machine-specific paths and are capture infrastructure,
    # so they must stay outside the versioned working-tree snapshots.
    _ensure_gitignore(repo_root, ".cursor/hooks.json", ".cursor/hooks/")

    script_rel = ".cursor/hooks/profact-hook.sh"
    script_path = repo_root / script_rel
    package_parent = Path(__file__).resolve().parent.parent.parent
    script = (
        "#!/usr/bin/env bash\n"
        "# Auto-generated by `profact start`. Forwards Cursor hook events to profact.\n"
        f'export PYTHONPATH="{package_parent}:$PYTHONPATH"\n'
        f'exec "{sys.executable}" -m profact.cli hook\n'
    )
    script_path.write_text(script)
    script_path.chmod(
        script_path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH
    )

    config_path = cursor_dir / "hooks.json"
    config: dict = {"version": 1, "hooks": {}}
    if config_path.exists():
        try:
            loaded = json.loads(config_path.read_text())
            if isinstance(loaded, dict):
                config = loaded
        except json.JSONDecodeError:
            pass
    config.setdefault("version", 1)
    hooks = config.setdefault("hooks", {})
    if not isinstance(hooks, dict):
        hooks = config["hooks"] = {}

    for event in HANDLED_EVENTS:
        entries = hooks.setdefault(event, [])
        if not isinstance(entries, list):
            entries = hooks[event] = []
        already = any(
            isinstance(entry, dict) and entry.get("command") == script_rel
            for entry in entries
        )
        if not already:
            entries.append({"command": script_rel})

    config_path.write_text(json.dumps(config, indent=2) + "\n")
    return script_rel


def handle(repo_root: Path, event: dict) -> dict:
    """Apply one Cursor hook event to the store. Returns a hook response dict.

    All profact hooks are informational/fire-and-forget, so the response is
    always an empty object; callers must still fail open on any error.
    """
    _record_debug_event(repo_root, event)
    if not store.is_initialized(repo_root):
        return {}

    name = event.get("hook_event_name")
    if name == EVENT_PROMPT:
        _on_prompt(repo_root, event)
    elif name == EVENT_THOUGHT:
        _on_thought(repo_root, event)
    elif name == EVENT_RESPONSE:
        _on_response(repo_root, event)
    elif name == EVENT_STOP:
        with store.connect(repo_root) as conn:
            _finalize_open(repo_root, conn)
    elif name == EVENT_SESSION_END:
        with store.connect(repo_root) as conn:
            _finalize_open(repo_root, conn)
        # Capture manual work performed after the last finalized prompt when
        # Cursor gives us a session boundary. Edits made after sessionEnd remain
        # visible as a dirty tree until the next prompt reconciles them.
        human_edits.reconcile(repo_root)
    return {}


def _record_debug_event(repo_root: Path, event: dict) -> None:
    """Best-effort raw event probe enabled by ``PROFACT_HOOK_DEBUG``."""
    if not os.environ.get("PROFACT_HOOK_DEBUG"):
        return
    try:
        log_path = store.profact_dir(repo_root) / "hook-events.log"
        log_path.parent.mkdir(parents=True, exist_ok=True)
        with log_path.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(event) + "\n")
    except Exception:
        # Hook debugging must never interfere with capture.
        pass


def _ensure_gitignore(repo_root: Path, *entries: str) -> None:
    gitignore = repo_root / ".gitignore"
    lines = gitignore.read_text().splitlines() if gitignore.exists() else []
    to_add = [entry for entry in entries if entry not in lines]
    if not to_add:
        return
    with gitignore.open("a") as handle:
        if lines and lines[-1].strip():
            handle.write("\n")
        for entry in to_add:
            handle.write(f"{entry}\n")


def _on_prompt(repo_root: Path, event: dict) -> None:
    branch = git_ops.current_branch(repo_root)
    prompt_text = event.get("prompt") or ""
    prompt_ref = store.write_object(repo_root, prompt_text) if prompt_text else None

    # Close a prompt whose stop event was lost before looking for human work.
    with store.connect(repo_root) as conn:
        _finalize_open(repo_root, conn)

    # Everything between the previous finalized snapshot and this prompt is one
    # human version, regardless of how many files or saves were involved.
    reconciliation = human_edits.reconcile(repo_root, branch)
    parent_id = store.read_head(repo_root, branch)
    with store.connect(repo_root) as conn:
        version = store.create_version(
            conn,
            type="prompt",
            git_branch=branch,
            parent_id=parent_id,
            tree_before=reconciliation.tree,
            prompt_ref=prompt_ref,
            model=event.get("model"),
            generation_id=event.get("generation_id"),
            conversation_id=event.get("conversation_id"),
        )
    store.write_head(repo_root, branch, version.id)


def _on_thought(repo_root: Path, event: dict) -> None:
    """Append one reasoning block to the open turn.

    A thinking model can emit several blocks per turn (interleaved with tool
    calls), so blocks are aggregated onto the same version, mirroring responses.
    """
    text = event.get("text") or ""
    if not text:
        return
    with store.connect(repo_root) as conn:
        version = _open_prompt(repo_root, conn)
        if version is None:
            return
        existing = (
            store.read_object(repo_root, version.thinking_ref)
            if version.thinking_ref
            else None
        )
        combined = f"{existing}\n{text}" if existing else text
        thinking_ref = store.write_object(repo_root, combined)
        conn.execute(
            "UPDATE versions SET thinking_ref = ?, thinking_source = ? WHERE id = ?",
            (thinking_ref, store.THINKING_CAPTURED, version.id),
        )
        conn.commit()


def _on_response(repo_root: Path, event: dict) -> None:
    text = event.get("text") or ""
    if not text:
        return
    with store.connect(repo_root) as conn:
        version = _open_prompt(repo_root, conn)
        if version is None:
            return
        existing = (
            store.read_object(repo_root, version.response_ref)
            if version.response_ref
            else None
        )
        combined = f"{existing}\n{text}" if existing else text
        response_ref = store.write_object(repo_root, combined)
        conn.execute(
            "UPDATE versions SET response_ref = ?, model = COALESCE(model, ?) WHERE id = ?",
            (response_ref, event.get("model"), version.id),
        )
        conn.commit()


def _finalize_open(repo_root: Path, conn: sqlite3.Connection) -> None:
    """Snapshot tree_after + diff for the currently open turn, if any. Idempotent."""
    version = _open_prompt(repo_root, conn)
    if version is None:
        return
    tree_after = git_ops.write_tree(repo_root)
    diff = git_ops.diff_trees(repo_root, version.tree_before, tree_after)
    diff_ref = store.write_object(repo_root, diff) if diff.strip() else None
    # Stamp an explicit "no reasoning" marker if no thinking block ever arrived,
    # so history distinguishes "model can't/didn't think" from "not yet recorded".
    conn.execute(
        "UPDATE versions SET tree_after = ?, diff_ref = ?, "
        "thinking_source = COALESCE(thinking_source, ?) WHERE id = ?",
        (tree_after, diff_ref, store.THINKING_NONE, version.id),
    )
    conn.commit()


def _open_prompt(repo_root: Path, conn: sqlite3.Connection) -> store.Version | None:
    """The open turn = the HEAD `prompt` version not yet finalized (tree_after NULL)."""
    branch = git_ops.current_branch(repo_root)
    head = store.read_head(repo_root, branch, seed=False)
    if not head:
        return None
    version = store.get_version(conn, head)
    if version and version.type == "prompt" and version.tree_after is None:
        return version
    return None
